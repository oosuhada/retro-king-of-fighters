function measurePixelText(text, scale = 1) {
    return Math.max(0, text.length * 6 - 1) * scale;
}

function drawPixelText(ctx, text, x, y, options = {}) {
    const scale = options.scale || 1;
    const color = options.color || '#ffffff';
    const align = options.align || 'left';
    const shadowColor = options.shadowColor || null;
    const shadowOffset = options.shadowOffset || 1;
    const normalized = String(text).toUpperCase();
    const width = measurePixelText(normalized, scale);
    let startX = x;
    if (align === 'center') startX -= width / 2;
    if (align === 'right') startX -= width;

    const drawPass = (passColor, offsetX, offsetY) => {
        ctx.fillStyle = passColor;
        for (let charIndex = 0; charIndex < normalized.length; charIndex++) {
            const glyph = GLYPHS[normalized[charIndex]] || GLYPHS['?'];
            for (let row = 0; row < 7; row++) {
                for (let col = 0; col < 5; col++) {
                    if (glyph[row][col] !== '1') continue;
                    ctx.fillRect(
                        Math.round(startX + charIndex * 6 * scale + col * scale + offsetX),
                        Math.round(y + row * scale + offsetY),
                        scale,
                        scale
                    );
                }
            }
        }
    };

    if (shadowColor) drawPass(shadowColor, shadowOffset, shadowOffset);
    drawPass(color, 0, 0);
}

